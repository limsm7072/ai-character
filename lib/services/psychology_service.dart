class PsychologyService {
  static const _cacheKey = 'psychology_cache';
  static const _cacheDateKey = 'psychology_cache_date';
  static const _historyKey = 'psychology_history';

  final SharedPreferences _prefs;
  PsychologyTip? _cached;

  PsychologyService(this._prefs) {
    _loadCache();
  }

  void _loadCache() {
    final raw = _prefs.getString(_cacheKey);
    if (raw == null) return;
    try {
      _cached = PsychologyTip.fromJson(jsonDecode(raw));
    } catch (_) {}
  }

  PsychologyTip? getCached() {
    if (_cached == null) return null;
    final today = _todayStr();
    final cacheDate = _prefs.getString(_cacheDateKey) ?? '';
    if (cacheDate != today) return null;
    return _cached;
  }

  PsychologyTip generateTodayTip() {
    final today = DateTime.now();
    final todayStr = _todayStr();

    // 캐시 확인
    final cacheDate = _prefs.getString(_cacheDateKey) ?? '';
    if (cacheDate == todayStr && _cached != null) return _cached!;

    // seed 생성 (날짜 기반, 결정론적)
    final seed = today.year * 10000 + today.month * 100 + today.day;

    // 카테고리 선택 (날짜 기반 순환)
    final catIdx = _hash(seed + 7919) % PsychologyCategory.values.length;
    final category = PsychologyCategory.values[catIdx];

    // 해당 카테고리의 팁 필터링
    final categoryTips = _psychologyDB.where(
      (t) => t['category'] == category.name
    ).toList();

    // 히스토리에서 최근 사용 ID 추출 (중복 방지)
    final history = getHistory();
    final recentIds = history.take(30).map((t) => t.id).toSet();

    // 사용 안 한 팁 우선 선택
    var available = categoryTips.where((t) => !recentIds.contains(t['id'])).toList();
    if (available.isEmpty) available = categoryTips;

    // 해시 기반 선택
    final idx = _hash(seed + category.index * 131) % available.length;
    final selected = available[idx];

    final tip = PsychologyTip(
      id: selected['id'] as String,
      title: selected['title'] as String,
      category: category,
      description: selected['description'] as String,
      dailyTip: selected['dailyTip'] as String,
      lunaComment: selected['lunaComment'] as String,
      relatedKeywords: (selected['relatedKeywords'] as List).cast<String>(),
      date: todayStr,
    );

    // 캐시 저장
    _cached = tip;
    _prefs.setString(_cacheKey, jsonEncode(tip.toJson()));
    _prefs.setString(_cacheDateKey, todayStr);

    // 히스토리에 추가
    _addToHistory(tip);

    return tip;
  }

  List<PsychologyTip> getHistory() {
    final raw = _prefs.getString(_historyKey);
    if (raw == null) return [];
    try {
      final list = jsonDecode(raw) as List;
      return list.map((e) => PsychologyTip.fromJson(e as Map<String, dynamic>)).toList();
    } catch (_) {
      return [];
    }
  }

  void _addToHistory(PsychologyTip tip) {
    final history = getHistory();
    // 같은 날짜 엔트리 제거
    history.removeWhere((t) => t.date == tip.date);
    history.insert(0, tip);
    // 최근 60개만 유지
    final trimmed = history.take(60).toList();
    _prefs.setString(_historyKey, jsonEncode(trimmed.map((t) => t.toJson()).toList()));
  }

  String _todayStr() {
    final now = DateTime.now();
    return '${now.year}-${now.month.toString().padLeft(2, '0')}-${now.day.toString().padLeft(2, '0')}';
  }

  static int _hash(int value) {
    var h = value & 0x7FFFFFFF;
    h = ((h >> 16) ^ h) * 0x45d9f3b;
    h = ((h >> 16) ^ h) * 0x45d9f3b;
    h = (h >> 16) ^ h;
    return h & 0x7FFFFFFF;
  }

